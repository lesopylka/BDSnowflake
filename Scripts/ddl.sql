BEGIN;

CREATE SCHEMA IF NOT EXISTS star;

CREATE TABLE IF NOT EXISTS star.dim_country (
    country_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_city (
    city_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name  TEXT NOT NULL,
    country_id INTEGER NOT NULL REFERENCES star.dim_country (country_id),
    UNIQUE (city_name, country_id)
);

CREATE TABLE IF NOT EXISTS star.dim_pet_type (
    pet_type_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_type_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_pet_breed (
    pet_breed_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breed_name   TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_product_category (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_pet_category (
    pet_category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_category_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_brand (
    brand_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_color (
    color_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_size (
    size_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    size_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_material (
    material_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS star.dim_date (
    date_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_date   DATE NOT NULL UNIQUE,
    year_num    INTEGER NOT NULL,
    quarter_num INTEGER NOT NULL CHECK (quarter_num BETWEEN 1 AND 4),
    month_num   INTEGER NOT NULL CHECK (month_num BETWEEN 1 AND 12),
    day_num     INTEGER NOT NULL CHECK (day_num BETWEEN 1 AND 31),
    month_name  TEXT NOT NULL,
    CHECK (year_num = EXTRACT(YEAR FROM full_date)),
    CHECK (quarter_num = EXTRACT(QUARTER FROM full_date)),
    CHECK (month_num = EXTRACT(MONTH FROM full_date)),
    CHECK (day_num = EXTRACT(DAY FROM full_date))
);

CREATE TABLE IF NOT EXISTS star.dim_supplier (
    supplier_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name TEXT,
    contact_name  TEXT,
    email         TEXT NOT NULL UNIQUE,
    phone         TEXT,
    address       TEXT,
    city_id       INTEGER REFERENCES star.dim_city (city_id)
);

CREATE TABLE IF NOT EXISTS star.dim_customer (
    customer_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   TEXT,
    last_name    TEXT,
    age          INTEGER CHECK (age >= 0),
    email        TEXT NOT NULL UNIQUE,
    postal_code  TEXT,
    country_id   INTEGER REFERENCES star.dim_country (country_id),
    pet_type_id  INTEGER REFERENCES star.dim_pet_type (pet_type_id),
    pet_breed_id INTEGER REFERENCES star.dim_pet_breed (pet_breed_id),
    pet_name     TEXT
);

CREATE TABLE IF NOT EXISTS star.dim_seller (
    seller_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  TEXT,
    last_name   TEXT,
    email       TEXT NOT NULL UNIQUE,
    postal_code TEXT,
    country_id  INTEGER REFERENCES star.dim_country (country_id)
);

CREATE TABLE IF NOT EXISTS star.dim_store (
    store_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name TEXT,
    location   TEXT,
    state_name TEXT,
    phone      TEXT,
    email      TEXT NOT NULL UNIQUE,
    city_id    INTEGER REFERENCES star.dim_city (city_id)
);

CREATE TABLE IF NOT EXISTS star.dim_product (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_nk      TEXT NOT NULL UNIQUE,
    product_name    TEXT,
    price           NUMERIC(12, 2) CHECK (price >= 0),
    stock_quantity  INTEGER CHECK (stock_quantity >= 0),
    weight          NUMERIC(12, 2) CHECK (weight >= 0),
    rating          NUMERIC(4, 2) CHECK (rating BETWEEN 0 AND 5),
    reviews         INTEGER CHECK (reviews >= 0),
    description     TEXT,
    release_date    DATE,
    expiry_date     DATE,
    category_id     INTEGER REFERENCES star.dim_product_category (category_id),
    pet_category_id INTEGER REFERENCES star.dim_pet_category (pet_category_id),
    brand_id        INTEGER REFERENCES star.dim_brand (brand_id),
    color_id        INTEGER REFERENCES star.dim_color (color_id),
    size_id         INTEGER REFERENCES star.dim_size (size_id),
    material_id     INTEGER REFERENCES star.dim_material (material_id),
    supplier_id     INTEGER REFERENCES star.dim_supplier (supplier_id)
);

CREATE TABLE IF NOT EXISTS star.fact_sales (
    sale_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date_id     INTEGER NOT NULL REFERENCES star.dim_date (date_id),
    customer_id      INTEGER NOT NULL REFERENCES star.dim_customer (customer_id),
    seller_id        INTEGER NOT NULL REFERENCES star.dim_seller (seller_id),
    product_id       INTEGER NOT NULL REFERENCES star.dim_product (product_id),
    store_id         INTEGER NOT NULL REFERENCES star.dim_store (store_id),
    sale_quantity    INTEGER NOT NULL CHECK (sale_quantity > 0),
    sale_total_price NUMERIC(14, 2) NOT NULL CHECK (sale_total_price >= 0)
);

COMMIT;